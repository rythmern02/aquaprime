import fs from "fs";
import path from "path";

/** Deployment manifest shared by the frontend, the keeper and the scripts. */
export interface DeploymentFile {
  chainId: number;
  network: string;
  deployBlock?: number;
  oracleMode: "operator" | "chainlink";
  contracts: Record<string, string>;
  roles: Record<string, string>;
  strategies?: {
    maker: string;
    creditLine?: { hash: string; aprBps: number; salt: number; amount: string };
    backstop?: { order: { maker: string; traits: string; data: string }; hash: string; discountBps: number; amount: string };
    amm?: { order: { maker: string; traits: string; data: string }; hash: string; amounts: string[]; tokens: string[] };
  };
}

export const DEPLOYMENTS_DIR = path.join(__dirname, "..", "..", "frontend", "src", "config", "deployments");

/**
 * A chain can host several markets (e.g. Sepolia's canonical Chainlink market and a labelled demo market with
 * an operator oracle). The default market is keyed by chain id; others by `<chainId>-<market>`. Scripts pick a
 * market with MARKET=<name>, the frontend with NEXT_PUBLIC_MARKET=<name>.
 */
export const marketKey = (chainId: number, market = process.env.MARKET) => (market ? `${chainId}-${market}` : String(chainId));

export function deploymentPath(chainId: number, market?: string) {
  return path.join(DEPLOYMENTS_DIR, `${marketKey(chainId, market)}.json`);
}

export function readDeployment(chainId: number, market?: string): DeploymentFile {
  return JSON.parse(fs.readFileSync(deploymentPath(chainId, market), "utf8"));
}

export function writeDeployment(chainId: number, data: Partial<DeploymentFile>, market?: string) {
  fs.mkdirSync(DEPLOYMENTS_DIR, { recursive: true });
  let prev: Partial<DeploymentFile> = {};
  try { prev = readDeployment(chainId, market); } catch { /* first write */ }
  const merged = { ...prev, ...data };
  // a fresh deploy invalidates previously seeded strategies
  if (data.contracts && prev.contracts && data.contracts.registry !== prev.contracts.registry) delete merged.strategies;
  fs.writeFileSync(deploymentPath(chainId, market), JSON.stringify(merged, null, 2) + "\n");
  writeIndex();
}

/** Regenerates deployments/index.ts so the frontend picks up every deployed chain automatically. */
export function writeIndex() {
  const ids = fs.readdirSync(DEPLOYMENTS_DIR).filter((f) => /^\d+(-[a-z0-9]+)?\.json$/.test(f)).map((f) => f.replace(".json", "")).sort();
  const v = (id: string) => `d${id.replace(/-/g, "_")}`;
  const src = "// AUTO-GENERATED by scripts/lib/deployment-file.ts\n" +
    ids.map((id) => `import ${v(id)} from "./${id}.json";`).join("\n") +
    `\n\nexport const DEPLOYMENTS: Record<string, unknown> = { ${ids.map((id) => `"${id}": ${v(id)}`).join(", ")} };\n`;
  fs.writeFileSync(path.join(DEPLOYMENTS_DIR, "index.ts"), src);
}
