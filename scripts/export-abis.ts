/** Exports the ABIs the frontend/keeper need into frontend/src/abi/generated.ts (typed `as const`). */
import fs from "fs";
import path from "path";

const root = path.join(__dirname, "..");
const wanted: Record<string, string> = {
  aqua: "artifacts/@1inch/aqua/src/Aqua.sol/Aqua.json",
  router: "artifacts/contracts/AquaPrimeRouter.sol/AquaPrimeRouter.json",
  registry: "artifacts/contracts/CreditPositionRegistry.sol/CreditPositionRegistry.json",
  executor: "artifacts/contracts/LiquidationExecutor.sol/LiquidationExecutor.json",
  builder: "artifacts/contracts/StrategyBuilder.sol/StrategyBuilder.json",
  priceFeed: "artifacts/contracts/oracles/OperatorPriceFeed.sol/OperatorPriceFeed.json",
  token: "artifacts/@1inch/swap-vm/test/mocks/TokenMockDecimals.sol/TokenMockDecimals.json",
};

let out = "// AUTO-GENERATED by scripts/export-abis.ts — do not edit\n";
for (const [name, rel] of Object.entries(wanted)) {
  const { abi } = JSON.parse(fs.readFileSync(path.join(root, rel), "utf8"));
  out += `export const ${name}Abi = ${JSON.stringify(abi)} as const;\n`;
}
const dest = path.join(root, "frontend", "src", "abi", "generated.ts");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(root, dest)}`);
